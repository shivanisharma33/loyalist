export function SocialIcon({ name, size = 16, className = "" }: { name: string; size?: number; className?: string }) {
  const n = name.toLowerCase();
  if (n.includes("linkedin")) return <LinkedInIcon size={size} className={className} />;
  if (n.includes("twitter") || n.includes("x")) return <XTwitterIcon size={size} className={className} />;
  if (n.includes("facebook")) return <FacebookIcon size={size} className={className} />;
  if (n.includes("youtube")) return <YouTubeIcon size={size} className={className} />;
  if (n.includes("instagram")) return <InstagramIcon size={size} className={className} />;
  return null;
}
